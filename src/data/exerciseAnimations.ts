export interface ExerciseAnimationSpec {
  id: string;
  label: string;
  cueSummary: string;
  muscleTarget: MuscleTarget;
  muscleLabel: string;
  stage: StageProp;
  equipment: EquipmentProp;
  durationMs: number;
  thumbnailT: number;
  isIsometric?: boolean;
  keyframes: PoseState[];
}

function p(x: number, y: number): Point {
  return {x, y};
}

function lerp(a: number, b: number, t: number): number {
  return a + (b - a) * t;
}

function lerpPoint(a: Point, b: Point, t: number): Point {
  return {x: lerp(a.x, b.x, t), y: lerp(a.y, b.y, t)};
}

function easeInOutSine(t: number): number {
  return -(Math.cos(Math.PI * t) - 1) / 2;
}

export function interpolatePose(keyframes: PoseState[], tNormalized: number): PoseState {
  if (keyframes.length === 0) {
    throw new Error('Exercise animation requires at least one keyframe.');
  }
  if (keyframes.length === 1) {
    return keyframes[0];
  }

  const t = ((tNormalized % 1) + 1) % 1;
  const segmentCount = keyframes.length - 1;
  const scaled = t * segmentCount;
  const idx = Math.min(segmentCount - 1, Math.floor(scaled));
  const localT = easeInOutSine(scaled - idx);
  const a = keyframes[idx];
  const b = keyframes[idx + 1];

  return {
    head: lerpPoint(a.head, b.head, localT),
    neck: lerpPoint(a.neck, b.neck, localT),
    shoulderL: lerpPoint(a.shoulderL, b.shoulderL, localT),
    shoulderR: lerpPoint(a.shoulderR, b.shoulderR, localT),
    elbowL: lerpPoint(a.elbowL, b.elbowL, localT),
    elbowR: lerpPoint(a.elbowR, b.elbowR, localT),
    wristL: lerpPoint(a.wristL, b.wristL, localT),
    wristR: lerpPoint(a.wristR, b.wristR, localT),
    hipL: lerpPoint(a.hipL, b.hipL, localT),
    hipR: lerpPoint(a.hipR, b.hipR, localT),
    kneeL: lerpPoint(a.kneeL, b.kneeL, localT),
    kneeR: lerpPoint(a.kneeR, b.kneeR, localT),
    ankleL: lerpPoint(a.ankleL, b.ankleL, localT),
    ankleR: lerpPoint(a.ankleR, b.ankleR, localT),
  };
}

export function getRepPhaseLabel(spec: ExerciseAnimationSpec, tNormalized: number): string {
  if (spec.isIsometric) return 'Isometric Brace · Steady Hold';
  const t = ((tNormalized % 1) + 1) % 1;
  if (t < 0.15 || t > 0.85) return 'Starting Position';
  if (t >= 0.15 && t < 0.44) return 'Concentric · Drive';
  if (t >= 0.44 && t <= 0.58) return 'Peak Contraction';
  return 'Eccentric · Controlled Return';
}

// Helper: standing side-facing silhouette builder (facing right)
function standingSidePose(opts: {
  leanX?: number;
  hipDropY?: number;
  kneeForwardX?: number;
  elbowL: Point;
  elbowR: Point;
  wristL: Point;
  wristR: Point;
  kneeL?: Point;
  kneeR?: Point;
  ankleL?: Point;
  ankleR?: Point;
  headOffset?: Point;
}): PoseState {
  const lean = opts.leanX ?? 0;
  const drop = opts.hipDropY ?? 0;
  const hipBase = p(112 - lean * 0.3, 98 + drop);
  const shoulderBase = p(114 + lean, 56 + drop * 0.85);
  return {
    head: p(
      shoulderBase.x + 3 + (opts.headOffset?.x ?? 0),
      shoulderBase.y - 17 + (opts.headOffset?.y ?? 0)
    ),
    neck: p(shoulderBase.x + 1, shoulderBase.y - 5),
    shoulderL: p(shoulderBase.x - 4, shoulderBase.y),
    shoulderR: p(shoulderBase.x + 4, shoulderBase.y + 1),
    elbowL: opts.elbowL,
    elbowR: opts.elbowR,
    wristL: opts.wristL,
    wristR: opts.wristR,
    hipL: p(hipBase.x - 3, hipBase.y),
    hipR: p(hipBase.x + 3, hipBase.y),
    kneeL: opts.kneeL ?? p(hipBase.x + (opts.kneeForwardX ?? 2), 127 + drop * 0.4),
    kneeR: opts.kneeR ?? p(hipBase.x + 5 + (opts.kneeForwardX ?? 2), 127 + drop * 0.4),
    ankleL: opts.ankleL ?? p(109, 155),
    ankleR: opts.ankleR ?? p(117, 155),
  };
}

// Helper: standing front-facing silhouette builder
function standingFrontPose(opts: {
  stanceHalf?: number;
  hipDropY?: number;
  torsoTiltX?: number;
  elbowL: Point;
  elbowR: Point;
  wristL: Point;
  wristR: Point;
  kneeOut?: number;
}): PoseState {
  const sh = opts.stanceHalf ?? 14;
  const drop = opts.hipDropY ?? 0;
  const tilt = opts.torsoTiltX ?? 0;
  const kOut = opts.kneeOut ?? 2;
  return {
    head: p(120 + tilt * 1.15, 37 + drop * 0.9),
    neck: p(120 + tilt * 0.9, 49 + drop * 0.9),
    shoulderL: p(104 + tilt, 55 + drop * 0.85),
    shoulderR: p(136 + tilt, 55 + drop * 0.85),
    elbowL: opts.elbowL,
    elbowR: opts.elbowR,
    wristL: opts.wristL,
    wristR: opts.wristR,
    hipL: p(110, 96 + drop),
    hipR: p(130, 96 + drop),
    kneeL: p(108 - kOut, 127 + drop * 0.45),
    kneeR: p(132 + kOut, 127 + drop * 0.45),
    ankleL: p(120 - sh, 155),
    ankleR: p(120 + sh, 155),
  };
}

